const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('public/section-state.js', 'utf8');
const load = suffix => import('data:text/javascript;base64,' + Buffer.from(source + '\n//' + suffix).toString('base64'));
(async () => {
  const values = new Map(), sessions = new Map();
  const storage = map => ({ getItem: key => map.get(key) ?? null, setItem: (key, value) => map.set(key, value) });
  global.window = { localStorage: storage(values), sessionStorage: storage(sessions) };
  let module = await load('initial');
  assert.equal(module.sectionOpen(1), true);
  module.rememberSection(1, false);
  module.rememberSection(2, false);
  module.rememberSection(1, true);
  assert.equal(module.sectionOpen(1), true);
  assert.equal(module.sectionOpen(2), false);
  module = await load('reload');
  assert.equal(module.sectionOpen(2), false, 'restores on next page');
  assert.equal(module.sectionOpen(3), true, 'new sections open by default');
  module.rememberSection('../x', false);
  assert.equal(module.sectionOpen('../x'), true);
  assert.equal(values.size, 2);
  values.set('forbirds-section-4', 'garbage');
  assert.equal(module.sectionOpen(4), true);
  window.localStorage = { getItem() { throw Error(); }, setItem() { throw Error(); } };
  module = await load('session');
  assert.equal(module.sectionOpen(2), false);
  window.sessionStorage = window.localStorage;
  module = await load('blocked');
  assert.equal(module.sectionOpen(2), true);
  module.rememberSection(2, false);
  assert.equal(module.sectionOpen(2), false);
  console.log('Section state persistence, per-ID isolation, unknown IDs, storage fallback and disabled storage: OK');
})().catch(error => { console.error(error); process.exitCode = 1; });
